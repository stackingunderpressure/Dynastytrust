// Writes Tapit's fresh-address test fixture (tapit-wallet src/features/sign-request/fixtures/fresh-address-vault.json).
// Run from the repo root: node scripts/make-tapit-fresh-fixture.mjs "$PWD" <out.json>
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
const ROOT = process.argv[2];
process.env.SUPABASE_URL = 'https://x.supabase.co';
const F = (f) => new URL(`file://${ROOT}/netlify/functions/${f}`).href;
const { callWasm } = await import(F('_ranged-wasm.js'));
const { buildRangedSpend } = await import(F('_ranged-spend.js'));
const { HDKey } = await import(`file://${ROOT}/node_modules/@scure/bip32/lib/esm/index.js`);
const { mnemonicToSeedSync } = await import(`file://${ROOT}/node_modules/@scure/bip39/esm/index.js`);
const hex = (b) => Buffer.from(b).toString('hex');
const TESTNET = { private: 0x04358394, public: 0x043587cf };
const PATH = "m/48'/1'/0'/2'";
const key = (m) => { const root = HDKey.fromMasterSeed(mnemonicToSeedSync(m), TESTNET); const acct = root.derive(PATH);
  return { fingerprint: root.fingerprint.toString(16).padStart(8, '0'), xpub: acct.publicExtendedKey, pubkey: hex(acct.deriveChild(0).deriveChild(0).publicKey) }; };
const k1 = key('abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about');
const k2 = key('legal winner thank year wave sausage worth useful legal winner thank yellow');
const TAPIT_PRIV = '00'.repeat(31) + '01';
const TAPIT = '0279be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798';
const leaves = [
  { id: 'everyday', label: 'everyday', keys: [TAPIT, k1.pubkey], quorum: 1, unlock: { type: 'immediate' } },
  { id: 'later', label: 'later', keys: [k1.pubkey, k2.pubkey], quorum: 1, unlock: { type: 'after', blocks: 900_000 } },
];
const compiled = callWasm('/compile-leaves', { network: 'signet', leaves }).body;
assert.ok(compiled.ok, JSON.stringify(compiled));
const ranged = callWasm('/ranged-compile', { template: compiled.descriptor, network: 'signet', origins: [k1, k2].map(k => ({ fingerprint: k.fingerprint, account_path: PATH, xpub: k.xpub })) }).body;
assert.ok(ranged.ok, JSON.stringify(ranged));
const V = { id: '77777777-7777-7777-7777-777777777777', name: 'My Vault', status: 'compiled', network: 'signet', address: compiled.address,
  leaf_scripts: compiled.leaf_scripts, leaves: leaves.map(l => ({ id: l.id, unlock: l.unlock })),
  descriptor_version: 2, descriptor_multipath: ranged.multipath, descriptor_receive: ranged.receive, descriptor_change: ranged.change };
const addr = (b, i) => callWasm('/ranged-address', { multipath: V.descriptor_multipath, receive: V.descriptor_receive, change: V.descriptor_change, network: 'signet', branch: b, index: i }).body.address;
const TIP = 200_000;
const coin = (b, i, value, k) => ({ txid: k.toString(16).padStart(64, '0'), vout: 0, value, status: { confirmed: true, block_height: TIP - 10 }, address: addr(b, i), branch: b, index: i });
const supabase = { from: (t) => { const o = { select: () => o, eq: () => o, in: () => o, order: () => o, limit: () => o, then: (res) => res(t === 'vault_addresses' ? { data: [], error: null } : { data: [{ branch: 0, next_index: 6 }, { branch: 1, next_index: 3 }], error: null }), insert: async () => ({ error: null }) }; return o; }, rpc: async () => ({ data: 3, error: null }) };
const r = await buildRangedSpend({ supabase, vault: V, userId: 'u', body: { destination: addr(0, 30), amount_sats: 70_000, path: 'everyday' } },
  { coinsAt: async () => [coin(0, 0, 20_000, 1), coin(0, 5, 30_000, 2), coin(1, 2, 40_000, 3)], fetchTipHeight: async () => TIP, getFeeRate: async () => 2 });
assert.equal(r.status, 200, JSON.stringify(r.body));
// Only the path holding the Tapit key goes in the membership, like leafScriptsForRole.
const everydayAt0 = compiled.leaf_scripts.everyday;
assert.ok(everydayAt0.includes(TAPIT.slice(2)));
writeFileSync(process.argv[3], JSON.stringify({
  note: 'Generated by DynastyTrust compiler wasm + _ranged-spend.js (make-tapit-fixture.mjs, 2026-11-24): a fresh-address signet vault, path everyday = 1-of-2 [Tapit key, xpub key k1]; a spend combining receive/0, receive/5 and change/2.',
  tapit_private_key: TAPIT_PRIV, tapit_public_key: TAPIT.slice(2),
  vault_descriptor: V.descriptor_multipath, leaf_scripts: [everydayAt0],
  ranged_keys: [{ xpub: k1.xpub, key00: k1.pubkey.slice(2) }],
  wrong_xpub: k2.xpub,
  psbt_hex: r.body.psbt_hex, input_addresses: ['receive/0', 'receive/5', 'change/2'],
  change_address: r.body.summary.change_address,
  // The vault's change addresses 0..9 as output scripts (what a membership's
  // change list holds); the spend's change is one of them.
  change_scripts: Array.from({ length: 10 }, (_, i) => callWasm('/ranged-address', { multipath: V.descriptor_multipath, receive: V.descriptor_receive, change: V.descriptor_change, network: 'signet', branch: 1, index: i }).body.script_pubkey.toLowerCase()),
  // Receive addresses -- NOT change; a list of these must refuse the spend.
  receive_scripts: Array.from({ length: 10 }, (_, i) => callWasm('/ranged-address', { multipath: V.descriptor_multipath, receive: V.descriptor_receive, change: V.descriptor_change, network: 'signet', branch: 0, index: i }).body.script_pubkey.toLowerCase()),
}, null, 2) + '\n');
console.log('inputs', r.body.summary.input_count, 'combined', r.body.summary.addresses_combined);
